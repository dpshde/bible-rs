//! Stage route.bible adapter links (and icons) into `OUT_DIR` for `include_str!` /
//! `include_bytes!`.
//!
//! **Default (offline-safe):** copy the committed snapshot from `data/` into `OUT_DIR`.
//! **Opt-in refresh:** set `ROUTE_BIBLE_ADAPTERS=refresh` to pull
//! `{ROUTE_BIBLE_FEED}/latest.txt` + `manifest.json` + sha256-verified icons (default feed
//! `https://route.bible/adapters/v1`). Results are cached by version under `OUT_DIR/feed-cache/`.
//! Failed or sandboxed fetches warn and keep the vendored snapshot — default builds never hit
//! the network.
//!
//! `scripts/sync-adapters` sets `ROUTE_BIBLE_ADAPTERS_OUT` so a successful refresh is also
//! copied into `crates/core/data/` for committing.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let data = manifest_dir.join("data");
    let vendored_links = data.join("adapters.links.json");
    let staged_links = out_dir.join("adapters.links.json");
    let icons_out = out_dir.join("adapter-icons");
    let gen_icons = out_dir.join("open_in_icons_gen.rs");

    println!("cargo:rerun-if-changed={}", vendored_links.display());
    println!("cargo:rerun-if-changed={}", data.join("adapter-icons").display());
    println!("cargo:rerun-if-changed={}", data.join("adapter-icons.json").display());
    println!("cargo:rerun-if-changed={}", data.join("adapters.version").display());
    println!("cargo:rerun-if-env-changed=ROUTE_BIBLE_ADAPTERS");
    println!("cargo:rerun-if-env-changed=ROUTE_BIBLE_FEED");
    println!("cargo:rerun-if-env-changed=ROUTE_BIBLE_ADAPTERS_OUT");

    // Always start from the committed snapshot so sandboxed builds succeed.
    fs::copy(&vendored_links, &staged_links).expect("stage vendored adapters.links.json");
    stage_vendored_icons(&data.join("adapter-icons"), &icons_out);

    let refresh = env::var("ROUTE_BIBLE_ADAPTERS").ok().as_deref() == Some("refresh");
    if refresh {
        match try_refresh_feed(&out_dir, &staged_links, &icons_out) {
            Ok(version) => {
                println!("cargo:warning=route.bible adapters refresh ok (version {version})");
                if let Ok(export) = env::var("ROUTE_BIBLE_ADAPTERS_OUT")
                    && let Err(e) =
                        export_refresh(&PathBuf::from(export), &staged_links, &icons_out, &version)
                {
                    panic!("ROUTE_BIBLE_ADAPTERS_OUT export failed: {e}");
                }
            }
            Err(e) => {
                println!(
                    "cargo:warning=route.bible adapters refresh failed ({e}); using vendored snapshot in data/"
                );
                if env::var_os("ROUTE_BIBLE_ADAPTERS_OUT").is_some() {
                    panic!("route.bible adapters refresh required (ROUTE_BIBLE_ADAPTERS_OUT set): {e}");
                }
            }
        }
    }

    write_icons_module(&icons_out, &gen_icons);
}

fn stage_vendored_icons(src: &Path, dest: &Path) {
    let _ = fs::remove_dir_all(dest);
    fs::create_dir_all(dest).expect("create OUT_DIR/adapter-icons");
    if !src.is_dir() {
        return;
    }
    for entry in fs::read_dir(src).expect("read vendored adapter-icons") {
        let entry = entry.expect("adapter-icons entry");
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) == Some("png") {
            fs::copy(&path, dest.join(entry.file_name())).expect("copy icon");
        }
    }
}

fn write_icons_module(icons_dir: &Path, dest: &Path) {
    let mut ids: Vec<String> = fs::read_dir(icons_dir)
        .map(|rd| {
            rd.filter_map(|e| e.ok())
                .filter_map(|e| {
                    let p = e.path();
                    if p.extension().and_then(|x| x.to_str()) == Some("png") {
                        p.file_stem().map(|s| s.to_string_lossy().into_owned())
                    } else {
                        None
                    }
                })
                .collect()
        })
        .unwrap_or_default();
    ids.sort();
    let mut out = String::from(
        "/// Generated by bible-core build.rs — PNG bytes staged in OUT_DIR/adapter-icons.\n\
         pub fn png(id: &str) -> Option<&'static [u8]> {\n    match id {\n",
    );
    for id in &ids {
        out.push_str(&format!(
            "        \"{id}\" => Some(include_bytes!(concat!(env!(\"OUT_DIR\"), \"/adapter-icons/{id}.png\"))),\n"
        ));
    }
    out.push_str(
        "        _ => None,\n    }\n}\n\n\
         #[cfg(test)]\nmod tests {\n    use super::*;\n\n    #[test]\n    fn ships_featured_adapter_icons() {\n\
         for id in [\"bible-app\", \"bible-gateway\", \"logos\", \"got-questions\"] {\n\
             let bytes = png(id).unwrap_or_else(|| panic!(\"missing icon for {id}\"));\n\
             assert!(bytes.len() > 50 && bytes[0] == 0x89 && bytes[1..4] == *b\"PNG\", \"{id} should be PNG\");\n\
         }\n    }\n\n    #[test]\n    fn unknown_adapter_has_no_icon() {\n\
             assert!(png(\"not-a-real-adapter\").is_none());\n    }\n}\n",
    );
    fs::write(dest, out).expect("write open_in_icons_gen.rs");
}

#[derive(Debug)]
struct FeedError(String);
impl std::fmt::Display for FeedError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}
impl std::error::Error for FeedError {}

fn try_refresh_feed(out_dir: &Path, staged_links: &Path, icons_out: &Path) -> Result<String, FeedError> {
    let base = env::var("ROUTE_BIBLE_FEED").unwrap_or_else(|_| "https://route.bible/adapters/v1".into());
    let base = base.trim_end_matches('/').to_string();

    let latest_bytes = fetch(&base, "latest.txt")?;
    let version = String::from_utf8_lossy(&latest_bytes).trim().to_string();
    if version.is_empty() || version.contains('<') {
        return Err(FeedError(format!("bad latest.txt from {base}")));
    }

    let cache = out_dir.join("feed-cache").join(&version);
    fs::create_dir_all(&cache).map_err(|e| FeedError(e.to_string()))?;
    let manifest_path = cache.join("manifest.json");
    if !manifest_path.is_file() {
        let body = fetch(&base, "manifest.json")?;
        fs::write(&manifest_path, body).map_err(|e| FeedError(e.to_string()))?;
    }

    let manifest: serde_json::Value =
        serde_json::from_slice(&fs::read(&manifest_path).map_err(|e| FeedError(e.to_string()))?)
            .map_err(|e| FeedError(format!("manifest JSON: {e}")))?;

    validate_manifest(&manifest, &version)?;

    let links_cache = cache.join("adapters.links.json");
    if !links_cache.is_file() {
        let adapters =
            manifest.get("adapters").ok_or_else(|| FeedError("manifest.adapters missing".into()))?;
        let body = serde_json::to_vec_pretty(adapters).map_err(|e| FeedError(e.to_string()))?;
        fs::write(&links_cache, body).map_err(|e| FeedError(e.to_string()))?;
    }
    fs::copy(&links_cache, staged_links).map_err(|e| FeedError(e.to_string()))?;

    let icons_cache = cache.join("icons");
    fs::create_dir_all(&icons_cache).map_err(|e| FeedError(e.to_string()))?;
    let _ = fs::remove_dir_all(icons_out);
    fs::create_dir_all(icons_out).map_err(|e| FeedError(e.to_string()))?;

    let icons = manifest
        .get("icons")
        .and_then(|v| v.as_object())
        .ok_or_else(|| FeedError("manifest.icons must be an object".into()))?;

    let mut icon_records = Vec::new();
    for (id, meta) in icons {
        let path = meta
            .get("path")
            .and_then(|v| v.as_str())
            .ok_or_else(|| FeedError(format!("icons[{id}].path")))?;
        let expect = meta
            .get("sha256")
            .and_then(|v| v.as_str())
            .map(|s| s.to_ascii_lowercase())
            .ok_or_else(|| FeedError(format!("icons[{id}].sha256")))?;
        let dest = icons_cache.join(format!("{id}.png"));
        if !dest.is_file() {
            let body = fetch(&base, path)?;
            let got = sha256_hex(&body);
            if got != expect {
                return Err(FeedError(format!("icon {id} sha256 mismatch: got {got}, expected {expect}")));
            }
            fs::write(&dest, &body).map_err(|e| FeedError(e.to_string()))?;
        } else {
            let body = fs::read(&dest).map_err(|e| FeedError(e.to_string()))?;
            let got = sha256_hex(&body);
            if got != expect {
                return Err(FeedError(format!("cached icon {id} sha256 mismatch")));
            }
        }
        let body = fs::read(&dest).map_err(|e| FeedError(e.to_string()))?;
        fs::copy(&dest, icons_out.join(format!("{id}.png"))).map_err(|e| FeedError(e.to_string()))?;
        icon_records.push(serde_json::json!({
            "id": id,
            "file": format!("{id}.png"),
            "type": "png",
            "bytes": body.len(),
            "sha256": expect,
            "width": meta.get("width").and_then(|v| v.as_u64()).unwrap_or(64),
            "height": meta.get("height").and_then(|v| v.as_u64()).unwrap_or(64),
        }));
    }

    icon_records.sort_by(|a, b| a["id"].as_str().cmp(&b["id"].as_str()));
    let icons_json = serde_json::json!({
        "version": 1,
        "source": format!("route.bible adapters feed ({version})"),
        "size": 64,
        "icons": icon_records,
    });
    fs::write(
        cache.join("adapter-icons.json"),
        serde_json::to_vec_pretty(&icons_json).map_err(|e| FeedError(e.to_string()))?,
    )
    .map_err(|e| FeedError(e.to_string()))?;
    fs::write(cache.join("adapters.version"), format!("{version}\n"))
        .map_err(|e| FeedError(e.to_string()))?;

    Ok(version)
}

fn validate_manifest(manifest: &serde_json::Value, latest: &str) -> Result<(), FeedError> {
    let schema = manifest.get("schemaVersion").and_then(|v| v.as_u64());
    if schema != Some(1) {
        return Err(FeedError(format!("manifest schemaVersion={schema:?}, expected 1")));
    }
    for key in ["version", "generatedAt", "adapterCount", "adapters", "icons"] {
        if manifest.get(key).is_none() {
            return Err(FeedError(format!("manifest.json missing {key}")));
        }
    }
    let version = manifest
        .get("version")
        .and_then(|v| v.as_str())
        .ok_or_else(|| FeedError("manifest.version must be a string".into()))?
        .trim();
    if version != latest {
        return Err(FeedError(format!("manifest.version={version:?} != latest.txt={latest:?}")));
    }
    let adapters = manifest
        .pointer("/adapters/adapters")
        .and_then(|v| v.as_array())
        .ok_or_else(|| FeedError("manifest.adapters.adapters must be an array".into()))?;
    let count = manifest
        .get("adapterCount")
        .and_then(|v| v.as_u64())
        .ok_or_else(|| FeedError("manifest.adapterCount must be an integer".into()))?;
    if count as usize != adapters.len() {
        return Err(FeedError(format!("manifest.adapterCount={count} != len(adapters)={}", adapters.len())));
    }
    let icons = manifest
        .get("icons")
        .and_then(|v| v.as_object())
        .ok_or_else(|| FeedError("manifest.icons must be an object".into()))?;
    for (id, meta) in icons {
        let sha = meta
            .get("sha256")
            .and_then(|v| v.as_str())
            .ok_or_else(|| FeedError(format!("icons[{id}].sha256")))?;
        if sha.len() != 64 || !sha.chars().all(|c| c.is_ascii_hexdigit()) {
            return Err(FeedError(format!("icons[{id}].sha256 is not 64-char hex")));
        }
        if meta.get("path").and_then(|v| v.as_str()).is_none() {
            return Err(FeedError(format!("icons[{id}].path")));
        }
    }
    Ok(())
}

fn export_refresh(dest: &Path, links: &Path, icons: &Path, version: &str) -> Result<(), FeedError> {
    fs::create_dir_all(dest).map_err(|e| FeedError(e.to_string()))?;
    fs::copy(links, dest.join("adapters.links.json")).map_err(|e| FeedError(e.to_string()))?;

    let icons_dest = dest.join("adapter-icons");
    let _ = fs::remove_dir_all(&icons_dest);
    fs::create_dir_all(&icons_dest).map_err(|e| FeedError(e.to_string()))?;
    for entry in fs::read_dir(icons).map_err(|e| FeedError(e.to_string()))? {
        let entry = entry.map_err(|e| FeedError(e.to_string()))?;
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) == Some("png") {
            fs::copy(&path, icons_dest.join(entry.file_name())).map_err(|e| FeedError(e.to_string()))?;
        }
    }

    // Prefer the cached metadata next to the versioned feed cache if present; else rebuild.
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let cache = out_dir.join("feed-cache").join(version);
    for name in ["adapter-icons.json", "adapters.version"] {
        let src = cache.join(name);
        if src.is_file() {
            fs::copy(&src, dest.join(name)).map_err(|e| FeedError(e.to_string()))?;
        }
    }
    Ok(())
}

fn fetch(base: &str, rel: &str) -> Result<Vec<u8>, FeedError> {
    let rel = rel.trim_start_matches('/');
    let local = Path::new(base);
    if local.is_dir() || base.starts_with("file:") {
        let root = PathBuf::from(base.strip_prefix("file://").unwrap_or(base));
        let path = root.join(rel);
        let body = fs::read(&path).map_err(|e| FeedError(format!("read {}: {e}", path.display())))?;
        return Ok(body);
    }
    let url = format!("{base}/{rel}");
    http_get(&url)
}

fn http_get(url: &str) -> Result<Vec<u8>, FeedError> {
    let output = Command::new("curl")
        .args([
            "-fsSL",
            "--retry",
            "2",
            "--retry-delay",
            "1",
            "-A",
            "bible-rs-build/0.2 (adapters refresh)",
            url,
        ])
        .output()
        .map_err(|e| FeedError(format!("curl {url}: {e}")))?;
    if !output.status.success() {
        return Err(FeedError(format!("curl {url} exited {}", output.status.code().unwrap_or(-1))));
    }
    if output.stdout.starts_with(b"<!doctype") || output.stdout.starts_with(b"<!DOCTYPE") {
        return Err(FeedError(format!("{url} returned HTML, not the feed")));
    }
    Ok(output.stdout)
}

fn sha256_hex(bytes: &[u8]) -> String {
    sha256::digest(bytes)
}

mod sha256 {
    pub fn digest(data: &[u8]) -> String {
        let mut h: [u32; 8] =
            [0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19];
        let bit_len = (data.len() as u64) * 8;
        let mut buf = data.to_vec();
        buf.push(0x80);
        while (buf.len() % 64) != 56 {
            buf.push(0);
        }
        buf.extend_from_slice(&bit_len.to_be_bytes());
        for chunk in buf.chunks_exact(64) {
            let mut w = [0u32; 64];
            for i in 0..16 {
                w[i] = u32::from_be_bytes(chunk[i * 4..i * 4 + 4].try_into().unwrap());
            }
            for i in 16..64 {
                let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
                let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
                w[i] = w[i - 16].wrapping_add(s0).wrapping_add(w[i - 7]).wrapping_add(s1);
            }
            let mut a = h;
            for i in 0..64 {
                let s1 = a[4].rotate_right(6) ^ a[4].rotate_right(11) ^ a[4].rotate_right(25);
                let ch = (a[4] & a[5]) ^ ((!a[4]) & a[6]);
                let t1 = a[7].wrapping_add(s1).wrapping_add(ch).wrapping_add(K[i]).wrapping_add(w[i]);
                let s0 = a[0].rotate_right(2) ^ a[0].rotate_right(13) ^ a[0].rotate_right(22);
                let maj = (a[0] & a[1]) ^ (a[0] & a[2]) ^ (a[1] & a[2]);
                let t2 = s0.wrapping_add(maj);
                a[7] = a[6];
                a[6] = a[5];
                a[5] = a[4];
                a[4] = a[3].wrapping_add(t1);
                a[3] = a[2];
                a[2] = a[1];
                a[1] = a[0];
                a[0] = t1.wrapping_add(t2);
            }
            for i in 0..8 {
                h[i] = h[i].wrapping_add(a[i]);
            }
        }
        h.iter().map(|x| format!("{x:08x}")).collect()
    }

    #[rustfmt::skip]
    const K: [u32; 64] = [
        0x428a2f98,0x71374491,0xb5c0fbcf,0xe9b5dba5,0x3956c25b,0x59f111f1,0x923f82a4,0xab1c5ed5,
        0xd807aa98,0x12835b01,0x243185be,0x550c7dc3,0x72be5d74,0x80deb1fe,0x9bdc06a7,0xc19bf174,
        0xe49b69c1,0xefbe4786,0x0fc19dc6,0x240ca1cc,0x2de92c6f,0x4a7484aa,0x5cb0a9dc,0x76f988da,
        0x983e5152,0xa831c66d,0xb00327c8,0xbf597fc7,0xc6e00bf3,0xd5a79147,0x06ca6351,0x14292967,
        0x27b70a85,0x2e1b2138,0x4d2c6dfc,0x53380d13,0x650a7354,0x766a0abb,0x81c2c92e,0x92722c85,
        0xa2bfe8a1,0xa81a664b,0xc24b8b70,0xc76c51a3,0xd192e819,0xd6990624,0xf40e3585,0x106aa070,
        0x19a4c116,0x1e376c08,0x2748774c,0x34b0bcb5,0x391c0cb3,0x4ed8aa4a,0x5b9cca4f,0x682e6ff3,
        0x748f82ee,0x78a5636f,0x84c87814,0x8cc70208,0x90befffa,0xa4506ceb,0xbef9a3f7,0xc67178f2,
    ];
}
